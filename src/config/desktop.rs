use anyhow::{ensure, Context, Result};
use serde::{Deserialize, Serialize};
use std::{
    fmt::Write,
    path::{Component, Path},
};

#[derive(Clone, Debug, PartialEq, Deserialize, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct DesktopPreferences {
    pub wallpaper: String,
    pub gtk_theme: String,
    pub qt_style: QtStyle,
    pub locale: String,
    pub timezone: String,
    pub clock_24h: bool,
    pub qt_scale: f32,
    pub accessibility_bus: bool,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum QtStyle {
    #[default]
    System,
    Fusion,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AppColor {
    System,
    #[default]
    Dark,
    Light,
}

impl AppColor {
    #[cfg(target_os = "linux")]
    pub(crate) fn portal_value(self) -> u32 {
        match self {
            Self::System => 0,
            Self::Dark => 1,
            Self::Light => 2,
        }
    }
}

impl Default for DesktopPreferences {
    fn default() -> Self {
        Self {
            wallpaper: String::new(),
            gtk_theme: String::new(),
            qt_style: QtStyle::System,
            locale: String::new(),
            timezone: String::new(),
            clock_24h: true,
            qt_scale: 1.0,
            accessibility_bus: false,
        }
    }
}

impl DesktopPreferences {
    pub(super) fn validate(&self) -> Result<()> {
        ensure!(
            self.wallpaper.is_empty()
                || (self.wallpaper.len() <= 768
                    && !self.wallpaper.chars().any(char::is_control)
                    && Path::new(&self.wallpaper).is_absolute()
                    && Path::new(&self.wallpaper)
                        .extension()
                        .and_then(|ext| ext.to_str())
                        .is_some_and(|ext| matches!(
                            ext.to_ascii_lowercase().as_str(),
                            "png" | "jpg" | "jpeg" | "webp"
                        ))),
            "Choose an absolute path to a PNG, JPEG or WebP wallpaper"
        );
        ensure!(
            token(&self.locale, 80, b"_.-@"),
            "Enter an installed locale such as en_US.UTF-8"
        );
        ensure!(
            token(&self.gtk_theme, 80, b"_-:")
                && self.gtk_theme.matches(':').count() <= 1
                && !self.gtk_theme.starts_with(':')
                && !self.gtk_theme.ends_with(':'),
            "Enter a GTK theme name or a variant such as Adwaita:dark"
        );
        ensure!(
            token(&self.timezone, 100, b"_+-/")
                && Path::new(&self.timezone)
                    .components()
                    .all(|part| matches!(part, Component::Normal(_))),
            "Enter an IANA time zone such as Asia/Kolkata"
        );
        ensure!(
            self.qt_scale.is_finite() && (1.0..=2.0).contains(&self.qt_scale),
            "Qt app scale must be between 1 and 2"
        );
        Ok(())
    }

    pub(crate) fn validate_wallpaper(&self) -> Result<()> {
        if !self.wallpaper.is_empty() {
            let image = std::fs::metadata(&self.wallpaper)
                .context("The selected wallpaper could not be read")?;
            ensure!(
                image.is_file() && (1..=48 * 1024 * 1024).contains(&image.len()),
                "Choose a wallpaper image of up to 48 MiB"
            );
        }
        Ok(())
    }

    pub(crate) const ENV_HEADER: &'static str = "# Generated by Hyprlume Desktop Preferences.\n";

    pub(crate) fn environment(&self, installed_locales: &str, zoneinfo: &Path) -> Result<String> {
        self.validate()?;
        let locale_key = |value: &str| value.to_ascii_lowercase().replace('-', "");
        if !self.locale.is_empty() {
            ensure!(
                installed_locales
                    .lines()
                    .any(|locale| locale_key(locale.trim()) == locale_key(&self.locale)),
                "This locale has not been generated on the system"
            );
        }
        if !self.timezone.is_empty() {
            let zone = zoneinfo.join(&self.timezone);
            let mut signature = [0; 4];
            let mut file = std::fs::File::open(&zone).context("This time zone is not installed")?;
            std::io::Read::read_exact(&mut file, &mut signature)
                .context("Read the installed time zone")?;
            ensure!(&signature == b"TZif", "The selected time zone is invalid");
        }
        let mut text = Self::ENV_HEADER.to_owned();
        for (name, value) in [
            ("GTK_THEME", self.gtk_theme.as_str()),
            ("LANG", self.locale.as_str()),
            ("TZ", self.timezone.as_str()),
            (
                "QT_STYLE_OVERRIDE",
                if self.qt_style == QtStyle::Fusion {
                    "Fusion"
                } else {
                    ""
                },
            ),
            (
                "QT_LINUX_ACCESSIBILITY_ALWAYS_ON",
                if self.accessibility_bus { "1" } else { "" },
            ),
        ] {
            if !value.is_empty() {
                writeln!(text, "{name}={value}").unwrap();
            }
        }
        if self.qt_scale != 1.0 {
            writeln!(text, "QT_SCALE_FACTOR={}", self.qt_scale).unwrap();
        }
        Ok(text)
    }
}

fn token(value: &str, limit: usize, extras: &[u8]) -> bool {
    value.len() <= limit
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || extras.contains(&byte))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn session_profile_accepts_installed_values_and_rejects_injected_assignments() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("UTC"), b"TZif").unwrap();
        let mut settings = DesktopPreferences {
            locale: "en_US.UTF-8".into(),
            timezone: "UTC".into(),
            gtk_theme: "Adwaita:dark".into(),
            ..DesktopPreferences::default()
        };
        assert!(settings
            .environment("C\nen_US.utf8", dir.path())
            .unwrap()
            .contains("LANG=en_US.UTF-8\n"));
        assert!(settings.environment("C", dir.path()).is_err());
        settings.timezone = "../UTC".into();
        assert!(settings.validate().is_err());
        settings.timezone.clear();
        settings.gtk_theme = "Adwaita\nPATH=/tmp".into();
        assert!(settings.validate().is_err());
    }
}
